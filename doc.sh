# Main
# * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * *

# Parse command line arguments
while [[ $# -gt 0 ]]; do
    case $1 in
        -h|--help)
            usage
            exit 0
            ;;
        -c|--clean)
            CLEAN_FIRST=1
            shift
            ;;
        -p|--private)
            INCLUDE_PRIVATE=1
            shift
            ;;
        -v|--verbose)
            VERBOSE=1
            shift
            ;;
        -x|--extra)
            API_ONLY=0
            shift
            ;;
        -f|--format)
            if [[ -z "${2:-}" ]]; then
                error "Option $1 requires an argument"
            fi
            case "$2" in
                html|latex|man|xml)
                    OUTPUT_FORMAT="$2"
                    ;;
                *)
                    error "Invalid format: $2. Supported formats: html, latex, man, xml"
                    ;;
            esac
            shift 2
            ;;
        -o|--output)
            if [[ -z "${2:-}" ]]; then
                error "Option $1 requires an argument"
            fi
            OUTPUT_DIR="$2"
            shift 2
            ;;
        *)
            error "Unknown option: $1. Use -h for help."
            ;;
    esac
done

# Set trap for cleanup
trap cleanup EXIT

# Check prerequisites
check_doxygen

# Clean if requested
if [[ $CLEAN_FIRST -eq 1 ]]; then
    clean_docs
fi

# Generate documentation
generate_doxyfile "$DOXYFILE" "$INCLUDE_PRIVATE"
run_doxygen "$DOXYFILE"

log "Documentation generation completed successfully!"
