run_doxygen() {
    local doxyfile="$1"

    log "Generating documentation using Doxygen..."
    verbose "Output directory: $OUTPUT_DIR"
    verbose "Output format: $OUTPUT_FORMAT"

    if [[ $VERBOSE -eq 1 ]]; then
        doxygen "$doxyfile"
    else
        doxygen "$doxyfile" 2>/dev/null
    fi

    if [[ $? -eq 0 ]]; then
        log "Documentation generated successfully in $OUTPUT_DIR/$OUTPUT_FORMAT/"

        if [[ "$OUTPUT_FORMAT" = "html" ]]; then
            log "Open $OUTPUT_DIR/html/index.html in your browser to view the documentation"
        fi
    else
        error "Documentation generation failed"
    fi
}

cleanup() {
    if [[ -f "$DOXYFILE" ]]; then
        rm -f "$DOXYFILE"
        verbose "Cleaned up temporary Doxyfile: $DOXYFILE"
    fi
}

