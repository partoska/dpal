usage() {
    cat << EOF
Usage: $0 [OPTIONS]

Generate documentation for Daemon Pal using Doxygen.

OPTIONS:
    -h, --help          Show this help message
    -c, --clean         Clean existing documentation before generation
    -p, --private       Include private/internal documentation from source files
    -v, --verbose       Enable verbose output
    -f, --format FORMAT Set output format (html, latex, man, xml) [default: html]
    -o, --output DIR    Set output directory [default: docs]
    -x, --extra         Generate full documentation (not dpal.h and dpaltypes.h only)

EXAMPLES:
    $0                  Generate HTML documentation
    $0 -c               Clean and regenerate documentation
    $0 -p -v            Generate with private docs and verbose output
    $0 -f latex         Generate LaTeX documentation
    $0 -a               Generate API-only documentation (dpal.h and dpaltypes.h)

EOF
}

log() {
    echo "doc.sh: $*" >&2
}

verbose() {
    if [[ $VERBOSE -eq 1 ]]; then
        log "$*"
    fi
}

error() {
    log "ERROR: $*"
    exit 1
}

check_doxygen() {
    if ! command -v doxygen >/dev/null 2>&1; then
        error "Doxygen is not installed. Please install it first."
    fi

    verbose "Using Doxygen: $(doxygen --version)"
}

clean_docs() {
    if [[ -d "$OUTPUT_DIR" ]]; then
        log "Cleaning existing documentation in $OUTPUT_DIR/"
        rm -rf "$OUTPUT_DIR"
    fi
}

